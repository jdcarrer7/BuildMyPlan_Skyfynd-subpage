const modalOnlyServices = ['website-rental'];

// Helper function to get services by category
export const getServicesByCategory = (categoryId: string): Service[] => {
  return services.filter((service) => service.category === categoryId && !modalOnlyServices.includes(service.id));
};

// Helper function to get a single service by ID
export const getServiceById = (serviceId: string): Service | undefined => {
  return services.find((service) => service.id === serviceId);
};
